function t(key, vars) {
  let s = (I18N[LANG] && I18N[LANG][key]);
  if (s == null) s = I18N.de[key];
  if (s == null) return key;
  if (typeof s === "object") s = (vars && vars.n === 1) ? s.one : s.other;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? String(vars[k]) : m));
  return s;
}
function setLang(code) {
  LANG = I18N[code] ? code : "de";
  document.documentElement.lang = LANG;
}
/* Gerätesprache: Deutsch für de-*, sonst Englisch */
function detectLang() {
  const l = (navigator.languages && navigator.languages[0]) || navigator.language || "de";
  return /^de\b/i.test(l) ? "de" : "en";
}
